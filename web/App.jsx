import { Banner } from '@astryxdesign/core/Banner';
import { Card } from '@astryxdesign/core/Card';
import { Heading } from '@astryxdesign/core/Heading';
import { HStack } from '@astryxdesign/core/HStack';
import { Spinner } from '@astryxdesign/core/Spinner';
import { Text } from '@astryxdesign/core/Text';
import { VStack } from '@astryxdesign/core/VStack';
import { lazy, Suspense, useState } from 'react';
import { ErrorBoundary } from './components/ErrorBoundary.jsx';
import { ProfileForm } from './components/ProfileForm.jsx';
import { DEFAULT_PROFILE, PAGE_MAX_WIDTH } from './constants.js';
import { usePlace } from './hooks/usePlace.js';
import { usePlan } from './hooks/usePlan.js';

// Results (tables, lists, chat) are only needed once a plan exists, so they load on demand.
const Results = lazy(() => import('./components/Results.jsx'));

export function App() {
  const [status, setStatus] = useState('');
  const [profile, setProfile] = useState(DEFAULT_PROFILE);
  const [failedSubmits, setFailedSubmits] = useState(0);
  const place = usePlace(setStatus);
  const plan = usePlan({ resolvePlace: place.resolve, profile, announce: setStatus });

  function handleSubmit() {
    if (place.validate()) {
      setFailedSubmits((count) => count + 1);
      return;
    }
    plan.build();
  }

  return (
    <>
      <a className="skip-link" href="#main">
        Skip to main content
      </a>
      <VStack className="page" gap={6} paddingBlock={6} paddingInline={4} maxWidth={PAGE_MAX_WIDTH}>
        <VStack as="header" gap={1}>
          <Heading level={1}>SmogWise</Heading>
          <Text color="secondary">
            A clean-air plan for your household, built from live air quality where you live.
          </Text>
        </VStack>

        <VStack as="main" id="main" gap={5}>
          <Card padding={6}>
            <VStack gap={4}>
              <Heading level={2} id="form-title">
                Tell us about your household
              </Heading>
              <ProfileForm
                place={place}
                profile={profile}
                onProfileChange={setProfile}
                onSubmit={handleSubmit}
                isSubmitting={plan.isPlanning}
                failedSubmits={failedSubmits}
              />
            </VStack>
          </Card>

          <HStack gap={3} align="center" role="status" aria-live="polite">
            {plan.isPlanning && <Spinner size="sm" />}
            <Text>{status}</Text>
          </HStack>
          {plan.failure && <Banner role="alert" status="error" title={plan.failure} />}

          {plan.result && (
            <ErrorBoundary
              resetKey={plan.result}
              message="Something went wrong showing your plan. Reload the page and try again."
            >
              <Suspense
                fallback={
                  <VStack role="status">
                    <Spinner label="Loading your plan..." />
                  </VStack>
                }
              >
                <Results result={plan.result} planRequest={plan.planRequest} announce={setStatus} />
              </Suspense>
            </ErrorBoundary>
          )}
        </VStack>

        <VStack as="footer">
          <Text as="p" type="supporting">
            Air quality and forecasts from the Google Maps Platform Air Quality API. Guidance is generated by Gemini and
            is not medical advice.
          </Text>
        </VStack>
      </VStack>
    </>
  );
}
